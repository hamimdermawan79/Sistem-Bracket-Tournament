-- SQL Schema and Initial Seed for Supabase (Tournament 128)

CREATE TABLE IF NOT EXISTS teams (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  logo_url TEXT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW())
);

CREATE TABLE IF NOT EXISTS players (
  slot INTEGER PRIMARY KEY,
  name TEXT,
  team_id TEXT REFERENCES teams(id) ON DELETE SET NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW())
);

-- In case players table already exists, ensure team_id column is added:
ALTER TABLE players ADD COLUMN IF NOT EXISTS team_id TEXT REFERENCES teams(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS matches (
  id TEXT PRIMARY KEY,
  round INT NOT NULL,
  match_number INT NOT NULL,
  bracket_side TEXT NOT NULL,
  player1_slot INT REFERENCES players(slot),
  player2_slot INT REFERENCES players(slot),
  winner_slot INT REFERENCES players(slot),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW())
);

ALTER TABLE teams ENABLE ROW LEVEL SECURITY;
ALTER TABLE players ENABLE ROW LEVEL SECURITY;
ALTER TABLE matches ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public Read Teams" ON teams;
DROP POLICY IF EXISTS "Allow All Write Teams" ON teams;
DROP POLICY IF EXISTS "Public Read Players" ON players;
DROP POLICY IF EXISTS "Public Read Matches" ON matches;
DROP POLICY IF EXISTS "Allow All Write Players" ON players;
DROP POLICY IF EXISTS "Allow All Write Matches" ON matches;

CREATE POLICY "Public Read Teams" ON teams FOR SELECT USING (true);
CREATE POLICY "Allow All Write Teams" ON teams FOR ALL USING (true);
CREATE POLICY "Public Read Players" ON players FOR SELECT USING (true);
CREATE POLICY "Public Read Matches" ON matches FOR SELECT USING (true);
CREATE POLICY "Allow All Write Players" ON players FOR ALL USING (true);
CREATE POLICY "Allow All Write Matches" ON matches FOR ALL USING (true);

